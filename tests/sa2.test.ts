import { describe, expect, it } from 'vitest';
import { sa2Execute, sa2SeedToKey, sa2Algorithm } from '../src/platform/sa2';

// 测试向量来自 bri3d/sa2_seed_key（MIT）的单元测试，用来证明解释器实现正确。
describe('VAG SA2 seed/key 解释器', () => {
  it('测试向量 1', () => {
    const script = [0x68, 0x02, 0x81, 0x49, 0x93, 0xa5, 0x5a, 0x55, 0xaa, 0x4a, 0x05, 0x87, 0x81, 0x05, 0x95, 0x26, 0x68, 0x05, 0x82, 0x49, 0x84, 0x5a, 0xa5, 0xaa, 0x55, 0x87, 0x03, 0xf7, 0x80, 0x6a, 0x4c];
    expect(sa2Execute(script, 0x1a1b1c1d) >>> 0).toBe(0x6a37f02e);
  });

  it('测试向量 2', () => {
    const script = [0x68, 0x02, 0x81, 0x4a, 0x10, 0x68, 0x04, 0x93, 0x08, 0x08, 0x20, 0x09, 0x4a, 0x05, 0x87, 0x22, 0x12, 0x19, 0x54, 0x82, 0x49, 0x93, 0x07, 0x12, 0x20, 0x11, 0x82, 0x4a, 0x05, 0x87, 0x03, 0x11, 0x20, 0x10, 0x82, 0x4a, 0x01, 0x81, 0x49, 0x4c];
    expect(sa2Execute(script, 0xa04eb1ed) >>> 0).toBe(0x3c7876d8);
  });

  it('字节数组接口（大端）', () => {
    const script = [0x68, 0x02, 0x81, 0x49, 0x93, 0xa5, 0x5a, 0x55, 0xaa, 0x4a, 0x05, 0x87, 0x81, 0x05, 0x95, 0x26, 0x68, 0x05, 0x82, 0x49, 0x84, 0x5a, 0xa5, 0xaa, 0x55, 0x87, 0x03, 0xf7, 0x80, 0x6a, 0x4c];
    const key = sa2SeedToKey(script, Uint8Array.of(0x1a, 0x1b, 0x1c, 0x1d));
    expect([...key]).toEqual([0x6a, 0x37, 0xf0, 0x2e]);
  });

  it('包装成算法后可被解锁引擎调用', () => {
    const algo = sa2Algorithm('vag-sa2-demo', 'VAG SA2（示例脚本）', [0x68, 0x02, 0x81, 0x49, 0x93, 0xa5, 0x5a, 0x55, 0xaa, 0x4a, 0x05, 0x87, 0x81, 0x05, 0x95, 0x26, 0x68, 0x05, 0x82, 0x49, 0x84, 0x5a, 0xa5, 0xaa, 0x55, 0x87, 0x03, 0xf7, 0x80, 0x6a, 0x4c]);
    expect([...algo.compute(Uint8Array.of(0x1a, 0x1b, 0x1c, 0x1d))]).toEqual([0x6a, 0x37, 0xf0, 0x2e]);
  });

  it('未知操作码报错', () => {
    expect(() => sa2Execute([0xff], 0)).toThrow(/未知操作码/);
  });
});
